"""Generate the README results block from artifacts (no hand-entered numbers, PRD section 5.4).

The block between the markers in README.md is owned by this module. `python -m benchmark.regenerate`
rewrites it; `--check` fails if it differs.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START = "<!-- results:start (generated by python -m benchmark.regenerate; do not edit) -->"
END = "<!-- results:end -->"


def _pct(x):
    return "n/a" if x is None else f"{x * 100:.0f}%"


def _cell(i):
    return f"{i['k']}/{i['n']} ({_pct(i['rate'])}, 95% CI {_pct(i['lo'])} to {_pct(i['hi'])})"


def block() -> str:
    t = json.loads((ROOT / "artifacts/benchmark/tierA.json").read_text(encoding="utf-8"))
    h = t["held_out"]
    par_path = ROOT / "artifacts/benchmark/parity.json"
    par = json.loads(par_path.read_text(encoding="utf-8")) if par_path.exists() else None
    p = h["recall_count_preserving"]["paired"]["mcnemar_exact_p"]
    lines = [
        START,
        f"Tier A, held-out split: {h['n_weakening']} injected weakenings and {h['n_legit']} legitimate edits in "
        f"{len(t['provenance']['sources'])} real repositories. **Experimental, injected cases; not real-world performance.**",
        "",
        "| Held-out | PROVECODE | Count-based baseline (reimplementation) |",
        "|---|---|---|",
        f"| Count-preserving weakenings caught | {_cell(h['recall_count_preserving']['provecode'])} | "
        f"{_cell(h['recall_count_preserving']['baseline'])} |",
        f"| All weakenings caught | {_cell(h['recall']['provecode'])} | {_cell(h['recall']['baseline'])} |",
        f"| Count-reducing weakenings caught | {_cell(h['recall_not_count_preserving']['provecode'])} | "
        f"{_cell(h['recall_not_count_preserving']['baseline'])} |",
        f"| Legitimate edits blocked (PROVECODE) / flagged (baseline) | {_cell(h['legit_blocking']['provecode'])} | "
        f"{_cell(h['legit_flagged']['baseline'])} |",
        "",
        f"F1 (count-preserving recall above the baseline) is "
        f"**{'supported' if t['falsification']['F1']['supported'] else 'not supported'}** on Tier A "
        f"(exact McNemar p = {p:.2g})." if p is not None else "F1: not testable.",
        "W17–W19 (tautologies, swallowed assertions, `or True`) were blind spots by design. Rules S5 and B4, added "
        "after those results were seen, now catch "
        f"{sum(v['provecode_flagged'] for k, v in t['all']['by_pattern'].items() if k in ('W17', 'W18', 'W19'))} of "
        f"{sum(v['n'] for k, v in t['all']['by_pattern'].items() if k in ('W17', 'W18', 'W19'))}, so Tier A recall on "
        "them is not an unbiased estimate; Tier A-b below is the fresh test of those rules.",
    ]
    u_path = ROOT / "artifacts/benchmark/tierA_u.json"
    if u_path.exists():
        u = json.loads(u_path.read_text(encoding="utf-8"))
        uh = u["held_out"]
        ub = u["all"]["by_pattern"]
        lines += [
            "",
            f"Tier A-u (unittest-style tests, ADR 0009), held-out split: {uh['n_weakening']} injected weakenings and "
            f"{uh['n_legit']} legitimate edits in {len(u['provenance']['sources'])} other real repositories, frozen "
            "before the detector change. **Experimental, injected cases; not real-world performance.**",
            "",
            "| Held-out (Tier A-u) | PROVECODE | Count-based baseline (reimplementation) |",
            "|---|---|---|",
            f"| Count-preserving weakenings caught | {_cell(uh['recall_count_preserving']['provecode'])} | "
            f"{_cell(uh['recall_count_preserving']['baseline'])} |",
            f"| All weakenings caught | {_cell(uh['recall']['provecode'])} | {_cell(uh['recall']['baseline'])} |",
            f"| Count-reducing weakenings caught | {_cell(uh['recall_not_count_preserving']['provecode'])} | "
            f"{_cell(uh['recall_not_count_preserving']['baseline'])} |",
            f"| Legitimate edits blocked (PROVECODE) / flagged (baseline) | {_cell(uh['legit_blocking']['provecode'])} | "
            f"{_cell(uh['legit_flagged']['baseline'])} |",
            "",
            "The same blind spots in unittest form (U13–U14) are now caught in "
            f"{sum(v['provecode_flagged'] for k, v in ub.items() if k in ('U13', 'U14'))} of "
            f"{sum(v['n'] for k, v in ub.items() if k in ('U13', 'U14'))}, with the same caveat.",
        ]
    b_path = ROOT / "artifacts/benchmark/tierA_b.json"
    if b_path.exists():
        b = json.loads(b_path.read_text(encoding="utf-8"))
        bh = b["held_out"]
        lines += [
            "",
            f"Tier A-b (vacuous and swallowed checks, ADR 0011), held-out split: {bh['n_weakening']} injected "
            f"weakenings and {bh['n_legit']} legitimate near-misses in {len(b['provenance']['sources'])} further "
            "repositories, frozen before the S5/B4 rule code. **Experimental, injected cases; the patterns mirror the "
            "rules' stated targets, so this shows the rules work as specified, not real-world recall.**",
            "",
            "| Held-out (Tier A-b) | PROVECODE | Count-based baseline (reimplementation) |",
            "|---|---|---|",
            f"| Weakenings caught | {_cell(bh['recall']['provecode'])} | {_cell(bh['recall']['baseline'])} |",
            f"| Legitimate edits flagged | {_cell(bh['legit_flagged']['provecode'])} | "
            f"{_cell(bh['legit_flagged']['baseline'])} |",
        ]
    if par:
        lines.append(
            f"Browser parity: Pyodide {par['pyodide_version']} (Python {par['pyodide_python']}) matches CPython "
            f"{par['cpython_reference']} on {par['cases_compared']} of {par['cases_compared']} cases"
            + (" (" + ", ".join(f"Tier {x['tier']}: {x['cases_compared']}" for x in par["tiers"]) + ")"
               if par.get("tiers") else "")
            if par["identical"] else f"Browser parity: {len(par['mismatches'])} mismatches against CPython"
        )
        lines[-1] += "."
    lines.append(END)
    return "\n".join(lines)


def _render(text: str) -> str:
    a, b = text.index(START), text.index(END) + len(END)
    return text[:a] + block() + text[b:]


def write() -> None:
    text = README.read_text(encoding="utf-8")
    README.write_text(_render(text), encoding="utf-8", newline="\n")


def check() -> list[str]:
    text = README.read_text(encoding="utf-8").replace("\r\n", "\n")
    return [] if _render(text) == text else ["README.md results block differs from the artifacts"]
